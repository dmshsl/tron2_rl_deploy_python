"""Validated stand-up actor contract (47 observations / 10 actions); pydantic + yaml only.

Generated from the Isaac StandUp env fixture by
tron2_rl/scripts/rsl_rl/export_deploy_contract.py --policy standup; consumed by standup_policy.py.
"""

from pathlib import Path
from typing import Final, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, model_validator

# tron2_common.kinematics.NAMES; repeated so the contract validates without numpy/FK imports.
REFERENCE_JOINTS: Final = tuple(f"{name}_{side}_Joint" for side in ("L", "R")
                                for name in ("proximal_pitch", "proximal_roll", "proximal_yaw", "knee"))
OBSERVATION_BLOCKS: Final = (("base_ang_vel", 3), ("proj_gravity", 3), ("joint_pos", 8), ("joint_vel", 10),
                             ("last_action", 10), ("joint_target", 8), ("phase", 4), ("progress", 1))


class FrozenModel(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid", allow_inf_nan=False)


class CatchBody(FrozenModel):
    """One rigid body of the training articulation (Isaac nominal mass, CoM in the body frame)."""

    name: str
    mass: float = Field(ge=0)
    com: tuple[float, float, float]


class StandupCatch(FrozenModel):
    """Base catch region (tron2_rl/standup/catch.py, DESIGN decisions 13/14), held hold_seconds = success
    (decision 14: hold_seconds 0 = the first policy step in the region)."""

    height: float = Field(gt=0)
    offset_min: float
    offset_max: float
    pitch: float = Field(gt=0)
    roll: float = Field(gt=0)
    hip_roll: float = Field(gt=0)
    hip_yaw: float = Field(gt=0)
    manifold_tolerance: float = Field(gt=0)
    manifold: tuple[tuple[float, float, float], ...]  # (root height, hip pitch, knee), rad, increasing height
    joint_speed: float = Field(gt=0)  # ||qdot|| of the eight position joints
    wheel_speed: float = Field(gt=0)  # |qdot| per wheel
    wheel_radius: float = Field(gt=0)
    bodies: tuple[CatchBody, ...]
    heading: float | None = Field(default=None, gt=0)  # |heading error| bound (rad), heading-input contracts (v6)
    drift: float | None = Field(default=None, gt=0)  # |odometry displacement| bound (m), odometry-input contracts (v7)

    @model_validator(mode="after")
    def check_catch(self) -> "StandupCatch":
        if not self.offset_min < self.offset_max:
            raise ValueError("catch CoM offset window must be ordered")
        heights = [row[0] for row in self.manifold]
        if len(heights) < 2 or heights != sorted(heights):
            raise ValueError("catch manifold needs >= 2 rows with increasing height")
        if sum(body.mass for body in self.bodies) <= 0:
            raise ValueError("catch mass table is empty")
        return self


class StandupSeated(FrozenModel):
    """Sit-down success (tron2_rl/standup/sitdown.py, DESIGN decision 19), deploy signals: every position joint within
    pose_tolerance of pose (A'), ||qdot_10|| < joint_speed, tilt < tilt and the base resting on the floor (FK + IMU:
    the lowest base-hull point within base_floor_tolerance of the lowest wheel point), held hold_seconds."""

    pose: tuple[float, ...]
    pose_tolerance: float = Field(gt=0)
    joint_speed: float = Field(gt=0)
    tilt: float = Field(gt=0)
    base_floor_tolerance: float = Field(gt=0)
    hold_seconds: float = Field(gt=0)

    @model_validator(mode="after")
    def check_pose(self) -> "StandupSeated":
        if len(self.pose) != 8:
            raise ValueError("seated pose needs the eight position joints")
        return self


class StandupSuccess(FrozenModel):
    rule: Literal["height", "catch", "seated"] = "height"
    catch: StandupCatch | None = None
    seated: StandupSeated | None = None
    height: float = Field(gt=0)
    tilt: float = Field(gt=0)
    joint_speed: float = Field(gt=0)
    hold_seconds: float = Field(ge=0)  # rule "height" needs > 0; "catch" 0 = first step in the region
    wheel_level_tolerance: float = Field(gt=0)
    body_clearance: float = Field(ge=0)

    @model_validator(mode="after")
    def check_rule(self) -> "StandupSuccess":
        if (self.rule == "catch") != (self.catch is not None):
            raise ValueError("success rule 'catch' needs (only) the catch block")
        if (self.rule == "seated") != (self.seated is not None):
            raise ValueError("success rule 'seated' needs (only) the seated block")
        if self.rule == "height" and self.hold_seconds <= 0:
            raise ValueError("success rule 'height' needs hold_seconds > 0")
        return self


class StandupPolicyContract(FrozenModel):
    """Generated by tron2_rl/scripts/rsl_rl/export_deploy_contract.py --policy standup, or (policy "sitdown", success
    rule "seated") by tron2_rl/standup/export_sitdown.py."""

    schema_version: int
    policy: Literal["standup", "sitdown"]
    source_task: str
    checkpoint_sha256: str
    fixture_sha256: str
    source_code_sha256: dict[str, str]
    sdk_names: tuple[str, ...]
    position_names: tuple[str, ...]
    wheel_names: tuple[str, ...]
    position_sdk: tuple[int, ...]
    wheel_sdk: tuple[int, ...]
    standing: tuple[float, ...]
    target_lower: tuple[float, ...]
    target_upper: tuple[float, ...]
    kp: tuple[float, ...]
    kd: tuple[float, ...]
    physics_dt: float = Field(gt=0)
    decimation: int = Field(gt=0)
    policy_dt: float = Field(gt=0)
    v_max: float = Field(gt=0)
    windup: float = Field(gt=0)
    wheel_torque_scale: float = Field(gt=0)
    wheel_torque_cap: float = Field(gt=0)
    actor_size: int
    action_size: int
    observation_blocks: tuple[tuple[str, int], ...]
    ang_vel_scale: float
    joint_vel_scale: float
    observation_clip: float = Field(gt=0)
    phase: tuple[float, ...]
    progress: float
    # Reward variant v6 (tron2_rl/standup/DESIGN.md decision 17): the progress input carries the heading error
    # wrap(yaw - yaw at the stand-up start, i.e. at [기립] before the seated route) instead of the constant above.
    heading_input: bool = False
    # Reward variant v7 (decision 17 (f)): phase slots 0-1 carry the wheel-odometry displacement since the policy started
    # (tron2_common.wheel_odometry, start heading frame, m) instead of the constants above.
    odometry_input: bool = False
    episode_seconds: float = Field(gt=0)
    start_poses: tuple[tuple[float, ...], ...]
    start_tolerance: float = Field(gt=0, le=0.5)
    settle_seconds: float = Field(ge=0)
    success: StandupSuccess
    imu_to_base_rpy: tuple[float, float, float]
    notes: tuple[str, ...] = ()

    @model_validator(mode="after")
    def check_layout(self) -> "StandupPolicyContract":
        if len(self.sdk_names) != 10 or len(set(self.sdk_names)) != 10:
            raise ValueError("TRON2 SDK requires ten unique joints")
        if self.position_names != REFERENCE_JOINTS or len(self.wheel_names) != 2:
            raise ValueError("stand-up position joints must follow tron2_common.kinematics.NAMES")
        if [self.sdk_names[i] for i in self.position_sdk] != list(self.position_names) or \
                [self.sdk_names[i] for i in self.wheel_sdk] != list(self.wheel_names):
            raise ValueError("stand-up joint index maps disagree with the SDK names")
        for values in (self.standing, self.target_lower, self.target_upper, self.kp, self.kd, *self.start_poses):
            if len(values) != 8:
                raise ValueError("per-position-joint arrays must have eight entries")
        if any(low >= high for low, high in zip(self.target_lower, self.target_upper, strict=True)):
            raise ValueError("target clamp must be ordered")
        if min(self.kp) <= 0 or min(self.kd) <= 0:
            raise ValueError("position PD gains must be positive")
        if abs(self.policy_dt - self.physics_dt * self.decimation) > 1e-9:
            raise ValueError("policy period must match the training physics decimation")
        if self.observation_blocks != OBSERVATION_BLOCKS or sum(n for _, n in self.observation_blocks) != self.actor_size:
            raise ValueError("stand-up observation layout disagrees with the deploy builder")
        if self.action_size != 10 or len(self.phase) != 4 or not self.start_poses:
            raise ValueError("stand-up action/phase layout disagrees with the deploy builder")
        if (self.policy == "sitdown") != (self.success.rule == "seated"):
            raise ValueError("the sit-down policy (only) uses the 'seated' success rule")
        return self


def load_standup_contract(path: Path) -> StandupPolicyContract:
    return StandupPolicyContract.model_validate(yaml.safe_load(path.read_text()))


def load_sitdown_contract(path: Path) -> StandupPolicyContract:
    contract = load_standup_contract(path)
    if contract.policy != "sitdown":
        raise ValueError(f"{path} is not a sit-down contract")
    return contract
